        public static string DisplayName(string status)
        {
            if (string.IsNullOrEmpty(status))
                return "-";
            return Names.TryGetValue(status.Trim(), out var name) ? name : $"状态{status}";
        }

        /// <summary>
        /// 面板灯：0 正常 / 1 中间 / 2 故障。
        /// </summary>
        public static int PanelLevel(string status)
        {
            if (!TryParse(status, out int v))
                return 1;

            // 正常 / 完成 / 空闲 / 充电 / 合法作业态
            if (v is 1 or 4 or 6 or 7 or 8 or 9 or 162 or 203 or 246 or 247 or 248)
                return 0;

            // 执行中 / 暂停 / 遇障边界 / 自检与模式切换等中间态
            if (v is 2 or 5 or 10 or 36 or 39 or 80 or 89 or 90 or 109
                or 110 or 113 or 115 or 116 or 118 or 120 or 130
                or 151 or 152 or 160 or 200 or 201 or 202 or 240
                or 245 or 254)
                return 1;

            if (v is >= 81 and <= 85)
                return 1;

            // 任务异常 / 异常段 / 指令错误 / 失败与告警
            if (v == 3)
                return 2;
            if (v is >= 11 and <= 38)
                return 2;
            if (v is >= 91 and <= 104)
                return 2;
            if (v is 111 or 112 or 114 or 117 or 119 or 121 or 122)
                return 2;
            if (v is 150 or 153 or 154 or 155 or 156 or 161)
                return 2;
            if (v is >= 205 and <= 236)
                return 2;
            if (v is >= 241 and <= 243)
                return 2;
            if (v is 249 or 250)
                return 2;

            return 1;
        }

        private static bool TryParse(string status, out int value)
        {
            return int.TryParse(status, NumberStyles.Integer, CultureInfo.InvariantCulture, out value);
        }
